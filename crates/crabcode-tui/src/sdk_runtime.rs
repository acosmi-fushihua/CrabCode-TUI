impl std::error::Error for ProtocolViolation {}

pub fn classify_envelope(value: &Value) -> Result<EnvelopeClass, ProtocolViolation> {
    let object = value.as_object().ok_or_else(|| ProtocolViolation {
        reason: "stdout envelope is not a JSON object".to_string(),
    })?;
    let top_level =
        object
            .get("type")
            .and_then(Value::as_str)
            .ok_or_else(|| ProtocolViolation {
                reason: "stdout envelope omitted a string type".to_string(),
            })?;
    match top_level {
        "assistant" => Ok(EnvelopeClass::Assistant),
        "user" => Ok(EnvelopeClass::User),
        "progress" => {
            validate_direct_message_identity(object, "direct query progress")?;
            string_field(object, "toolUseID", "direct query progress")?;
            string_field(object, "parentToolUseID", "direct query progress")?;
            let data = object
                .get("data")
                .and_then(Value::as_object)
                .ok_or_else(|| ProtocolViolation {
                    reason: "direct query progress omitted object field `data`".to_string(),
                })?;
            let progress_type = string_field(data, "type", "direct query progress.data")?;
            if !KNOWN_DIRECT_PROGRESS_TYPES.contains(&progress_type.as_str()) {
                return Ok(EnvelopeClass::Unclassified {
                    observed_type: Some(top_level.to_string()),
                    observed_system_subtype: Some(progress_type),
                });
            }
            Ok(EnvelopeClass::DirectProgress { progress_type })
        }
        "attachment" => {
            validate_direct_message_identity(object, "direct query attachment")?;
            optional_string_field(object, "toolUseID", "direct query attachment")?;
            let attachment = object
                .get("attachment")
                .and_then(Value::as_object)
                .ok_or_else(|| ProtocolViolation {
                    reason: "direct query attachment omitted object field `attachment`".to_string(),
                })?;
            let attachment_type =
                string_field(attachment, "type", "direct query attachment.attachment")?;
            if !KNOWN_DIRECT_ATTACHMENT_TYPES.contains(&attachment_type.as_str()) {
                return Ok(EnvelopeClass::Unclassified {
                    observed_type: Some(top_level.to_string()),
                    observed_system_subtype: Some(attachment_type),
                });
            }
            Ok(EnvelopeClass::DirectAttachment { attachment_type })
        }
        "result" => Ok(EnvelopeClass::Result),
        "system" => {
            let subtype = object
                .get("subtype")
                .and_then(Value::as_str)
                .ok_or_else(|| ProtocolViolation {
                    reason: "system envelope omitted a string subtype".to_string(),
                })?;
            if object.contains_key("timestamp") {
                validate_direct_message_identity(object, "direct query system")?;
                return Ok(classify_direct_system_subtype(subtype)
                    .map(EnvelopeClass::DirectSystem)
                    .unwrap_or_else(|| EnvelopeClass::Unclassified {
                        observed_type: Some(top_level.to_string()),
                        observed_system_subtype: Some(subtype.to_string()),
                    }));
            }
            Ok(classify_system_subtype(subtype)
                .map(EnvelopeClass::System)
                .unwrap_or_else(|| EnvelopeClass::Unclassified {
                    observed_type: Some(top_level.to_string()),
                    observed_system_subtype: Some(subtype.to_string()),
                }))
        }
        "stream_event" => Ok(EnvelopeClass::StreamEvent {
            event_type: object
                .get("event")
                .and_then(|event| event.get("type"))
                .and_then(Value::as_str)
                .map(str::to_string),
        }),
        "stream_request_start" => {
            optional_string_field(object, "uuid", "direct query stream_request_start")?;
            Ok(EnvelopeClass::DirectStreamRequestStart)
        }
        "tombstone" => {
            optional_string_field(object, "uuid", "direct query tombstone")?;
            let message = object
                .get("message")
                .and_then(Value::as_object)
                .ok_or_else(|| ProtocolViolation {
                    reason: "direct query tombstone omitted object field `message`".to_string(),
                })?;
            let message_type = string_field(message, "type", "direct query tombstone.message")?;
            if !KNOWN_DIRECT_MESSAGE_TYPES.contains(&message_type.as_str()) {
                return Err(ProtocolViolation {
                    reason: format!("unknown direct query tombstone message type `{message_type}`"),
                });
            }
            Ok(EnvelopeClass::DirectTombstone { message_type })
        }
        "tool_progress" => Ok(EnvelopeClass::ToolProgress),
        "auth_status" => Ok(EnvelopeClass::AuthStatus),
        "tool_use_summary" => Ok(EnvelopeClass::ToolUseSummary),
        "rate_limit_event" => Ok(EnvelopeClass::RateLimitEvent),
        "prompt_suggestion" => Ok(EnvelopeClass::PromptSuggestion),
        "streamlined_text" => Ok(EnvelopeClass::StreamlinedText),
        "streamlined_tool_use_summary" => Ok(EnvelopeClass::StreamlinedToolUseSummary),
        "control_request" => {
            let request_id = string_field(object, "request_id", "control_request")?;
            let request = object
                .get("request")
                .and_then(Value::as_object)
                .ok_or_else(|| ProtocolViolation {
                    reason: "control_request omitted an object request".to_string(),
                })?;
            let subtype = string_field(request, "subtype", "control_request.request")?;
            if !known_control_request_subtype(&subtype) {
                return Err(ProtocolViolation {
                    reason: format!("unknown control request subtype `{subtype}`"),
                });
            }
            Ok(EnvelopeClass::ControlRequest {
                request_id,
                subtype,
            })
        }
        "control_response" => {
            let response = object
                .get("response")
                .and_then(Value::as_object)
                .ok_or_else(|| ProtocolViolation {
                    reason: "control_response omitted an object response".to_string(),
                })?;
            let request_id = string_field(response, "request_id", "control_response.response")?;
            let outcome = string_field(response, "subtype", "control_response.response")?;
            if !matches!(outcome.as_str(), "success" | "error") {
                return Err(ProtocolViolation {
                    reason: format!("unknown control response subtype `{outcome}`"),
                });
            }
            match outcome.as_str() {
                "success" => {
                    if response
                        .get("response")
                        .is_some_and(|body| !body.is_object())
                    {
                        return Err(ProtocolViolation {
                            reason: "successful control_response response body must be an object"
                                .to_string(),
                        });
                    }
                }
                "error" => {
                    string_field(response, "error", "control_response.response")?;
                    if response
                        .get("pending_permission_requests")
                        .is_some_and(|pending| !pending.is_array())
                    {
                        return Err(ProtocolViolation {
                            reason: "error control_response pending_permission_requests must be an array"
                                .to_string(),
                        });
                    }
                }
                _ => unreachable!("the response subtype allowlist was checked above"),
            }
            Ok(EnvelopeClass::ControlResponse {
                request_id,
                outcome,
            })
        }
        "control_cancel_request" => Ok(EnvelopeClass::ControlCancelRequest {
            request_id: string_field(object, "request_id", "control_cancel_request")?,
        }),
        PRIVATE_RUNTIME_RESULT_TYPE => Ok(classify_private_runtime_result(object)),
        "keep_alive" => Ok(EnvelopeClass::KeepAlive),
        unknown
            if unknown.starts_with("control_") || unknown.starts_with("crabcode_tui_runtime_") =>
        {
            Err(ProtocolViolation {
                reason: format!("unknown safety/control envelope type `{unknown}`"),
            })
        }
        // Additive presentation events must not terminate an otherwise valid
        // CrabCode runtime. Projection retains the raw frame and emits a
        // visible compatibility row. Control/private protocol namespaces are
        // rejected above, so this fallback cannot weaken their boundary.
        _ => Ok(unclassified(value)),
    }
}

fn string_field(
    object: &serde_json::Map<String, Value>,
    key: &str,
    context: &str,
) -> Result<String, ProtocolViolation> {
    object
        .get(key)
        .and_then(Value::as_str)
        .map(str::to_string)
        .ok_or_else(|| ProtocolViolation {
            reason: format!("{context} omitted string field `{key}`"),
        })
}

fn optional_string_field(
    object: &serde_json::Map<String, Value>,
    key: &str,
    context: &str,
) -> Result<(), ProtocolViolation> {
    if object.get(key).is_some_and(|value| !value.is_string()) {
        return Err(ProtocolViolation {
            reason: format!("{context} has non-string optional field `{key}`"),
        });
    }
    Ok(())
}

