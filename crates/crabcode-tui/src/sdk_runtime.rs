fn valid_private_retained_result(kind: &str, result: &serde_json::Map<String, Value>) -> bool {
    let valid_color = |value: Option<&Value>| {
        value.is_some_and(|value| {
            value.is_null()
                || value.as_str().is_some_and(|color| {
                    [
                        "red", "blue", "green", "yellow", "purple", "orange", "pink", "cyan",
                    ]
                    .contains(&color)
                })
        })
    };
    match kind {
        "retained.identity.snapshot" => {
            object_has_exact_fields(result, &["kind", "name", "color"], &[])
                && string_or_null(result.get("name"))
                && valid_color(result.get("color"))
        }
        "retained.color.updated" => {
            object_has_exact_fields(result, &["kind", "color"], &[])
                && valid_color(result.get("color"))
        }
        "retained.rename.updated" => {
            object_has_exact_fields(result, &["kind", "name"], &[])
                && result
                    .get("name")
                    .and_then(Value::as_str)
                    .is_some_and(|name| !name.is_empty())
        }
        "retained.vim.updated" => {
            object_has_exact_fields(result, &["kind", "editor_mode"], &[])
                && matches!(
                    result.get("editor_mode").and_then(Value::as_str),
                    Some("normal" | "vim")
                )
        }
        "retained.brief.updated" => {
            object_has_exact_fields(result, &["kind", "enabled", "reminder_injected"], &[])
                && result.get("enabled").is_some_and(Value::is_boolean)
                && result
                    .get("reminder_injected")
                    .is_some_and(Value::is_boolean)
        }
        "retained_command_error" => {
            object_has_exact_fields(result, &["kind", "action_kind", "code"], &[])
                && result
                    .get("action_kind")
                    .and_then(Value::as_str)
                    .is_some_and(|action_kind| {
                        matches!(
                            action_kind,
                            "retained.identity.snapshot"
                                | "retained.color.apply"
                                | "retained.rename.apply"
                                | "retained.vim.toggle"
                                | "retained.brief.toggle"
                        )
                    })
                && result
                    .get("code")
                    .and_then(Value::as_str)
                    .is_some_and(|code| {
                        matches!(
                            code,
                            "argument_required"
                                | "invalid_argument"
                                | "teammate_restricted"
                                | "name_generation_unavailable"
                                | "command_unavailable"
                                | "not_entitled"
                                | "surface_unavailable"
                                | "authority_failure"
                        )
                    })
        }
        _ => false,
    }
}

fn private_action_fields(
    object: &serde_json::Map<String, Value>,
    kind: &str,
    required: &[&str],
    optional: &[&str],
) -> Result<(), SendError> {
    if object_has_exact_fields(object, required, optional) {
        Ok(())
    } else {
        Err(SendError::InvalidEnvelope(format!(
            "private runtime action `{kind}` has unknown or missing fields"
        )))
    }
}

fn private_required_string(
    object: &serde_json::Map<String, Value>,
    kind: &str,
    field: &str,
) -> Result<(), SendError> {
    if object
        .get(field)
        .and_then(Value::as_str)
        .is_some_and(|value| !value.is_empty())
    {
        Ok(())
    } else {
        Err(SendError::InvalidEnvelope(format!(
            "private runtime action `{kind}` has invalid string field `{field}`"
        )))
    }
}

fn private_optional_nullable_string(
    object: &serde_json::Map<String, Value>,
    kind: &str,
    field: &str,
) -> Result<(), SendError> {
    match object.get(field) {
        None | Some(Value::Null) => Ok(()),
        Some(Value::String(value)) if !value.is_empty() => Ok(()),
        _ => Err(SendError::InvalidEnvelope(format!(
            "private runtime action `{kind}` has invalid optional string field `{field}`"
        ))),
    }
}

fn private_required_bool(
    object: &serde_json::Map<String, Value>,
    kind: &str,
    field: &str,
) -> Result<(), SendError> {
    if object.get(field).is_some_and(Value::is_boolean) {
        Ok(())
    } else {
        Err(SendError::InvalidEnvelope(format!(
            "private runtime action `{kind}` has invalid boolean field `{field}`"
        )))
    }
}

fn private_required_string_choice(
    object: &serde_json::Map<String, Value>,
    kind: &str,
    field: &str,
    choices: &[&str],
) -> Result<(), SendError> {
    if object
        .get(field)
        .and_then(Value::as_str)
        .is_some_and(|value| choices.contains(&value))
    {
        Ok(())
    } else {
        Err(SendError::InvalidEnvelope(format!(
            "private runtime action `{kind}` has invalid enum field `{field}`"
        )))
    }
}

fn validate_custom_model_input(value: Option<&Value>, kind: &str) -> Result<(), SendError> {
    let object = value.and_then(Value::as_object).ok_or_else(|| {
        SendError::InvalidEnvelope(format!(
            "private runtime action `{kind}` has invalid custom model input"
        ))
    })?;
    private_action_fields(
        object,
        kind,
        &[
            "brand",
            "protocol",
            "baseUrl",
            "modelId",
            "contextWindow",
            "maxOutputTokens",
            "enabled",
        ],
        &[
            "apiKey",
            "displayName",
            "supportsThinking",
            "supportsTools",
            "supportsJsonMode",
            "supportsVision",
            "isDefault",
        ],
    )?;
    for field in ["brand", "protocol", "baseUrl", "modelId"] {
        private_required_string(object, kind, field)?;
    }
    for field in ["apiKey", "displayName"] {
        if object.contains_key(field) {
            private_required_string(object, kind, field)?;
        }
    }
    for field in ["contextWindow", "maxOutputTokens"] {
        if object
            .get(field)
            .and_then(Value::as_u64)
            .is_none_or(|value| value == 0)
        {
            return Err(SendError::InvalidEnvelope(format!(
                "private runtime action `{kind}` has invalid positive integer field `{field}`"
            )));
        }
    }
    for field in [
        "enabled",
        "supportsThinking",
        "supportsTools",
        "supportsJsonMode",
        "supportsVision",
        "isDefault",
    ] {
        if object.get(field).is_some_and(|value| !value.is_boolean()) {
            return Err(SendError::InvalidEnvelope(format!(
                "private runtime action `{kind}` has invalid boolean field `{field}`"
            )));
        }
    }
    Ok(())
}

