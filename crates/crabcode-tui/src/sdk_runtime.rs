    fn submit_nonblocking(
        &self,
        value: Value,
        reserve_correlation: impl FnOnce(
            &mut CorrelationState,
            OutboundDeliveryId,
        ) -> Result<OutboundCorrelationIntent, SendError>,
    ) -> Result<OutboundDeliveryId, OutboundSubmitError> {
        if self.writer_budget.is_closed() || self.writer_tx.is_none() {
            return Err(SendError::Closed.into());
        }
        let encoded = serde_json::to_vec(&value).map_err(SendError::Encode)?;
        if encoded.len() > self.max_outbound_frame_bytes {
            return Err(SendError::FrameTooLarge {
                limit: self.max_outbound_frame_bytes,
                actual: encoded.len(),
            }
            .into());
        }
        let deadline = Instant::now()
            .checked_add(self.outbound_send_timeout)
            .expect("validated outbound send timeout must fit a monotonic deadline");
        let mut state = self
            .nonblocking_outbound
            .lock()
            .unwrap_or_else(|poison| poison.into_inner());
        if !state.has_capacity_for(encoded.len()) {
            return Err(state.queue_full_error());
        }
        let delivery_id = state.reserve_delivery_id()?;
        let correlation = reserve_correlation(
            &mut self
                .correlations
                .lock()
                .unwrap_or_else(|poison| poison.into_inner()),
            delivery_id,
        )?;
        state.reserved_bytes = state.reserved_bytes.saturating_add(encoded.len());
        state.pending.push_back(PendingOutboundFrame {
            id: delivery_id,
            value,
            encoded,
            deadline,
            blocked_stage: SendTimeoutStage::ByteBudget,
            correlation,
        });
        drop(state);
        self.outbound_ready.notify_one();
        Ok(delivery_id)
    }

