fn validate_outbound_control_request(
    request_id: &str,
    request: &Value,
) -> Result<String, SendError> {
    if request_id.is_empty() {
        return Err(SendError::InvalidEnvelope(
            "control request id must not be empty".to_string(),
        ));
    }
    let subtype = request
        .get("subtype")
        .and_then(Value::as_str)
        .ok_or_else(|| {
            SendError::InvalidEnvelope(
                "control request payload omitted a string subtype".to_string(),
            )
        })?
        .to_string();
    if !known_control_request_subtype(&subtype) {
        return Err(SendError::InvalidEnvelope(format!(
            "unknown control request subtype `{subtype}`"
        )));
    }
    Ok(subtype)
}

fn unclassified(value: &Value) -> EnvelopeClass {
    EnvelopeClass::Unclassified {
        observed_type: value
            .get("type")
            .and_then(Value::as_str)
            .map(str::to_string),
        observed_system_subtype: value
            .get("subtype")
            .and_then(Value::as_str)
            .map(str::to_string),
    }
}

struct CorrelationState {
    outbound_requests: HashMap<String, String>,
    /// A non-blocking control request reserves its request id before writer
    /// admission. The reservation prevents duplicate submission without
    /// falsely claiming that the request is already on the wire.
    outbound_delivery_reservations: HashMap<String, OutboundDeliveryId>,
    private_runtime_actions: HashMap<String, String>,
    private_runtime_delivery_reservations: HashMap<String, OutboundDeliveryId>,
    reverse_requests: HashMap<String, ReverseRequest>,
    /// A reverse response remains pending until its writer ACK. This prevents
    /// two renderer actions from answering the same backend request while
    /// still allowing an inbound cancellation to invalidate a not-yet-admitted
    /// response deterministically.
    reverse_delivery_reservations: HashMap<String, ReverseDeliveryReservation>,
    next_reverse_generation: u64,
    shutdown_response_waiter: Option<String>,
    shutdown_response: Option<(String, String)>,
    max_pending_per_direction: usize,
}

struct ReverseRequest {
    subtype: String,
    generation: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct ReverseDeliveryReservation {
    generation: u64,
    delivery_id: OutboundDeliveryId,
}

impl CorrelationState {
    fn new(max_pending_per_direction: usize) -> Self {
        Self {
            outbound_requests: HashMap::new(),
            outbound_delivery_reservations: HashMap::new(),
            private_runtime_actions: HashMap::new(),
            private_runtime_delivery_reservations: HashMap::new(),
            reverse_requests: HashMap::new(),
            reverse_delivery_reservations: HashMap::new(),
            next_reverse_generation: 0,
            shutdown_response_waiter: None,
            shutdown_response: None,
            max_pending_per_direction,
        }
    }

    fn outbound_request_count(&self) -> usize {
        self.outbound_requests.len()
            + self
                .outbound_delivery_reservations
                .keys()
                .filter(|request_id| !self.outbound_requests.contains_key(*request_id))
                .count()
            + self.private_runtime_actions.len()
            + self
                .private_runtime_delivery_reservations
                .keys()
                .filter(|request_id| !self.private_runtime_actions.contains_key(*request_id))
                .count()
    }

    fn reverse_request_count(&self) -> usize {
        self.reverse_requests.len()
            + self
                .reverse_delivery_reservations
                .keys()
                .filter(|request_id| !self.reverse_requests.contains_key(*request_id))
                .count()
    }

    fn reserve_outbound_delivery(
        &mut self,
        request_id: &str,
        delivery_id: OutboundDeliveryId,
    ) -> Result<(), SendError> {
        if self.outbound_requests.contains_key(request_id)
            || self.outbound_delivery_reservations.contains_key(request_id)
            || self.private_runtime_actions.contains_key(request_id)
            || self
                .private_runtime_delivery_reservations
                .contains_key(request_id)
        {
            return Err(SendError::Correlation(format!(
                "duplicate outbound request id `{request_id}`"
            )));
        }
        if self.outbound_request_count() >= self.max_pending_per_direction {
            return Err(SendError::Correlation(format!(
                "outbound control request limit ({}) exceeded",
                self.max_pending_per_direction
            )));
        }
        let previous = self
            .outbound_delivery_reservations
            .insert(request_id.to_string(), delivery_id);
        debug_assert!(previous.is_none());
        Ok(())
    }

    fn reserve_private_runtime_delivery(
        &mut self,
        request_id: &str,
        delivery_id: OutboundDeliveryId,
    ) -> Result<(), SendError> {
        if self.private_runtime_actions.contains_key(request_id)
            || self
                .private_runtime_delivery_reservations
                .contains_key(request_id)
            || self.outbound_requests.contains_key(request_id)
            || self.outbound_delivery_reservations.contains_key(request_id)
        {
            return Err(SendError::Correlation(format!(
                "duplicate private runtime request id `{request_id}`"
            )));
        }
        if self.outbound_request_count() >= self.max_pending_per_direction {
            return Err(SendError::Correlation(format!(
                "outbound request limit ({}) exceeded",
                self.max_pending_per_direction
            )));
        }
        let previous = self
            .private_runtime_delivery_reservations
            .insert(request_id.to_string(), delivery_id);
        debug_assert!(previous.is_none());
        Ok(())
    }

    fn reserve_reverse_delivery(
        &mut self,
        request_id: &str,
        expected_subtype: &str,
        delivery_id: OutboundDeliveryId,
    ) -> Result<u64, SendError> {
        if self.reverse_delivery_reservations.contains_key(request_id) {
            return Err(SendError::Correlation(format!(
                "reverse request `{request_id}` already has a response awaiting delivery"
            )));
        }
        let pending = self.reverse_requests.get(request_id).ok_or_else(|| {
            SendError::Correlation(format!("no pending reverse request `{request_id}`"))
        })?;
        if pending.subtype != expected_subtype {
            return Err(SendError::Correlation(format!(
                "request `{request_id}` is `{}`, not `{expected_subtype}`",
                pending.subtype
            )));
        }
        let generation = pending.generation;
        self.reverse_delivery_reservations.insert(
            request_id.to_string(),
            ReverseDeliveryReservation {
                generation,
                delivery_id,
            },
        );
        Ok(generation)
    }

    fn prepare_nonblocking_admission(
        &mut self,
        delivery_id: OutboundDeliveryId,
        intent: &OutboundCorrelationIntent,
    ) -> Result<(), SendError> {
        match intent {
            OutboundCorrelationIntent::None => Ok(()),
            OutboundCorrelationIntent::ControlRequest {
                request_id,
                subtype,
            } => {
                if self.outbound_delivery_reservations.get(request_id) != Some(&delivery_id) {
                    return Err(SendError::Correlation(format!(
                        "outbound request `{request_id}` lost its delivery reservation"
                    )));
                }
                if self.outbound_requests.contains_key(request_id) {
                    return Err(SendError::Correlation(format!(
                        "duplicate outbound request id `{request_id}`"
                    )));
                }
                self.outbound_requests
                    .insert(request_id.clone(), subtype.clone());
                Ok(())
            }
            OutboundCorrelationIntent::PrivateRuntimeAction { request_id, kind } => {
                if self.private_runtime_delivery_reservations.get(request_id) != Some(&delivery_id)
                {
                    return Err(SendError::Correlation(format!(
                        "private runtime request `{request_id}` lost its delivery reservation"
                    )));
                }
                if self.private_runtime_actions.contains_key(request_id) {
                    return Err(SendError::Correlation(format!(
                        "duplicate private runtime request id `{request_id}`"
                    )));
                }
                self.private_runtime_actions
                    .insert(request_id.clone(), kind.clone());
                Ok(())
            }
            OutboundCorrelationIntent::ReverseResponse {
                request_id,
                generation,
            } => {
                let expected = ReverseDeliveryReservation {
                    generation: *generation,
                    delivery_id,
                };
                if self.reverse_delivery_reservations.get(request_id) != Some(&expected) {
                    return Err(SendError::Correlation(format!(
                        "reverse request `{request_id}` lost its response reservation"
                    )));
                }
                if self
                    .reverse_requests
                    .get(request_id)
                    .is_none_or(|pending| pending.generation != *generation)
                {
                    return Err(SendError::Correlation(format!(
                        "reverse request `{request_id}` was cancelled before response delivery"
                    )));
                }
                Ok(())
            }
        }
    }

    fn rollback_nonblocking_admission(
        &mut self,
        delivery_id: OutboundDeliveryId,
        intent: &OutboundCorrelationIntent,
    ) {
        match intent {
            OutboundCorrelationIntent::None => {}
            OutboundCorrelationIntent::ControlRequest {
                request_id,
                subtype,
            } => {
                if self.outbound_delivery_reservations.get(request_id) == Some(&delivery_id) {
                    self.outbound_delivery_reservations.remove(request_id);
                }
                if self.outbound_requests.get(request_id) == Some(subtype) {
                    self.outbound_requests.remove(request_id);
                }
            }
            OutboundCorrelationIntent::PrivateRuntimeAction { request_id, kind } => {
                if self.private_runtime_delivery_reservations.get(request_id) == Some(&delivery_id)
                {
                    self.private_runtime_delivery_reservations
                        .remove(request_id);
                }
                if self.private_runtime_actions.get(request_id) == Some(kind) {
                    self.private_runtime_actions.remove(request_id);
                }
            }
            OutboundCorrelationIntent::ReverseResponse {
                request_id,
                generation,
            } => {
                let expected = ReverseDeliveryReservation {
                    generation: *generation,
                    delivery_id,
                };
                if self.reverse_delivery_reservations.get(request_id) == Some(&expected) {
                    self.reverse_delivery_reservations.remove(request_id);
                }
            }
        }
    }

    fn undo_nonblocking_writer_admission(&mut self, intent: &OutboundCorrelationIntent) {
        match intent {
            OutboundCorrelationIntent::ControlRequest {
                request_id,
                subtype,
            } if self.outbound_requests.get(request_id) == Some(subtype) => {
                self.outbound_requests.remove(request_id);
            }
            OutboundCorrelationIntent::PrivateRuntimeAction { request_id, kind }
                if self.private_runtime_actions.get(request_id) == Some(kind) =>
            {
                self.private_runtime_actions.remove(request_id);
            }
            _ => {}
        }
    }

    fn finish_nonblocking_delivery(
        &mut self,
        delivery_id: OutboundDeliveryId,
        intent: &OutboundCorrelationIntent,
    ) {
        match intent {
            OutboundCorrelationIntent::None => {}
            OutboundCorrelationIntent::ControlRequest { request_id, .. } => {
                if self.outbound_delivery_reservations.get(request_id) == Some(&delivery_id) {
                    self.outbound_delivery_reservations.remove(request_id);
                }
            }
            OutboundCorrelationIntent::PrivateRuntimeAction { request_id, .. } => {
                if self.private_runtime_delivery_reservations.get(request_id) == Some(&delivery_id)
                {
                    self.private_runtime_delivery_reservations
                        .remove(request_id);
                }
            }
            OutboundCorrelationIntent::ReverseResponse {
                request_id,
                generation,
            } => {
                let expected = ReverseDeliveryReservation {
                    generation: *generation,
                    delivery_id,
                };
                if self.reverse_delivery_reservations.get(request_id) == Some(&expected) {
                    self.reverse_delivery_reservations.remove(request_id);
                }
                if self
                    .reverse_requests
                    .get(request_id)
                    .is_some_and(|pending| pending.generation == *generation)
                {
                    self.reverse_requests.remove(request_id);
                }
            }
        }
    }

    fn observe_inbound(
        &mut self,
        classification: &EnvelopeClass,
    ) -> Result<Option<RequestCorrelation>, String> {
        match classification {
            EnvelopeClass::ControlRequest {
                request_id,
                subtype,
            } => {
                if self.reverse_requests.contains_key(request_id)
                    || self.reverse_delivery_reservations.contains_key(request_id)
                {
                    return Err(format!(
                        "duplicate reverse control request id `{request_id}`"
                    ));
                }
                if self.reverse_request_count() >= self.max_pending_per_direction {
                    return Err(format!(
                        "reverse control request limit ({}) exceeded",
                        self.max_pending_per_direction
                    ));
                }
                let generation = self.next_reverse_generation;
                self.next_reverse_generation = self.next_reverse_generation.wrapping_add(1);
                self.reverse_requests.insert(
                    request_id.clone(),
                    ReverseRequest {
                        subtype: subtype.clone(),
                        generation,
                    },
                );
                Ok(Some(RequestCorrelation::ReverseRequestRegistered {
                    request_id: request_id.clone(),
                    subtype: subtype.clone(),
                }))
            }
            EnvelopeClass::ControlResponse {
                request_id,
                outcome,
            } => {
                if !self.outbound_requests.contains_key(request_id)
                    && self.outbound_delivery_reservations.contains_key(request_id)
                {
                    return Err(format!(
                        "control response `{request_id}` arrived before writer admission"
                    ));
                }
                Ok(Some(match self.outbound_requests.remove(request_id) {
                    Some(request_subtype) => {
                        if request_subtype == "end_session"
                            && self.shutdown_response_waiter.as_deref() == Some(request_id.as_str())
                        {
                            self.shutdown_response = Some((request_id.clone(), outcome.clone()));
                        }
                        RequestCorrelation::OutboundResponseMatched {
                            request_id: request_id.clone(),
                            request_subtype,
                        }
                    }
                    None => RequestCorrelation::OutboundResponseUnmatched {
                        request_id: request_id.clone(),
                    },
                }))
            }
            EnvelopeClass::ControlCancelRequest { request_id } => {
                Ok(Some(RequestCorrelation::ReverseRequestCancelled {
                    request_id: request_id.clone(),
                    request_subtype: self
                        .reverse_requests
                        .remove(request_id)
                        .map(|request| request.subtype),
                }))
            }
            EnvelopeClass::PrivateRuntimeResult { request_id, .. } => {
                let Some(request_id) = request_id else {
                    return Ok(None);
                };
                if !self.private_runtime_actions.contains_key(request_id)
                    && self
                        .private_runtime_delivery_reservations
                        .contains_key(request_id)
                {
                    return Err(format!(
                        "private runtime result `{request_id}` arrived before writer admission"
                    ));
                }
                Ok(Some(
                    match self.private_runtime_actions.remove(request_id) {
                        Some(action_kind) => RequestCorrelation::PrivateRuntimeResultMatched {
                            request_id: request_id.clone(),
                            action_kind,
                        },
                        None => RequestCorrelation::PrivateRuntimeResultUnmatched {
                            request_id: request_id.clone(),
                        },
                    },
                ))
            }
            _ => Ok(None),
        }
    }
}

struct ByteBudget {
    state: Mutex<ByteBudgetState>,
    changed: Condvar,
    capacity: usize,
}

struct ByteBudgetState {
    used: usize,
    closed: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BudgetAcquire {
    Acquired,
    Closed,
    Unavailable,
    TimedOut,
}

impl ByteBudget {
    fn new(capacity: usize) -> Self {
        Self {
            state: Mutex::new(ByteBudgetState {
                used: 0,
                closed: false,
            }),
            changed: Condvar::new(),
            capacity,
        }
    }

    fn acquire(&self, bytes: usize) -> bool {
        matches!(
            self.acquire_with_deadline(bytes, None),
            BudgetAcquire::Acquired
        )
    }

    fn acquire_until(&self, bytes: usize, deadline: Instant) -> BudgetAcquire {
        self.acquire_with_deadline(bytes, Some(deadline))
    }

    fn try_acquire(&self, bytes: usize) -> BudgetAcquire {
        if bytes > self.capacity {
            return BudgetAcquire::Closed;
        }
        let mut state = self
            .state
            .lock()
            .unwrap_or_else(|poison| poison.into_inner());
        if state.closed {
            return BudgetAcquire::Closed;
        }
        if state.used.saturating_add(bytes) > self.capacity {
            return BudgetAcquire::Unavailable;
        }
        state.used += bytes;
        BudgetAcquire::Acquired
    }

    fn acquire_with_deadline(&self, bytes: usize, deadline: Option<Instant>) -> BudgetAcquire {
        if bytes > self.capacity {
            return BudgetAcquire::Closed;
        }
        let mut state = self
            .state
            .lock()
            .unwrap_or_else(|poison| poison.into_inner());
        loop {
            if state.closed {
                return BudgetAcquire::Closed;
            }
            if deadline.is_some_and(|deadline| Instant::now() >= deadline) {
                return BudgetAcquire::TimedOut;
            }
            if state.used.saturating_add(bytes) <= self.capacity {
                state.used += bytes;
                return BudgetAcquire::Acquired;
            }
            state = if let Some(deadline) = deadline {
                let remaining = deadline.saturating_duration_since(Instant::now());
                if remaining.is_zero() {
                    return BudgetAcquire::TimedOut;
                }
                match self.changed.wait_timeout(state, remaining) {
                    Ok((state, _)) => state,
                    Err(poison) => poison.into_inner().0,
                }
            } else {
                self.changed
                    .wait(state)
                    .unwrap_or_else(|poison| poison.into_inner())
            };
        }
    }

    fn release(&self, bytes: usize) {
        let mut state = self
            .state
            .lock()
            .unwrap_or_else(|poison| poison.into_inner());
        state.used = state.used.saturating_sub(bytes);
        self.changed.notify_all();
    }

    fn close(&self) {
        let mut state = self
            .state
            .lock()
            .unwrap_or_else(|poison| poison.into_inner());
        state.closed = true;
        self.changed.notify_all();
    }

    fn is_closed(&self) -> bool {
        self.state
            .lock()
            .unwrap_or_else(|poison| poison.into_inner())
            .closed
    }
}

