static ACTIVE_RUNTIME_PROCESS_IDS: OnceLock<Mutex<HashSet<u32>>> = OnceLock::new();

fn active_runtime_process_ids() -> &'static Mutex<HashSet<u32>> {
    ACTIVE_RUNTIME_PROCESS_IDS.get_or_init(|| Mutex::new(HashSet::new()))
}

struct ActiveRuntimeRegistration {
    process_id: u32,
}

impl ActiveRuntimeRegistration {
    fn new(process_id: u32) -> Self {
        active_runtime_process_ids()
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .insert(process_id);
        Self { process_id }
    }
}

impl Drop for ActiveRuntimeRegistration {
    fn drop(&mut self) {
        active_runtime_process_ids()
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .remove(&self.process_id);
    }
}

fn try_for_each_active_runtime_process_id(
    registrations: Option<&Mutex<HashSet<u32>>>,
    mut visit: impl FnMut(u32),
) {
    let Some(registrations) = registrations else {
        return;
    };
    let registrations = match registrations.try_lock() {
        Ok(registrations) => registrations,
        Err(std::sync::TryLockError::Poisoned(error)) => error.into_inner(),
        Err(std::sync::TryLockError::WouldBlock) => return,
    };
    for &process_id in registrations.iter() {
        visit(process_id);
    }
}

/// Lock-bounded emergency variant used only by panic and repeated-signal
/// termination. If runtime registration is being mutated, immediate process
/// termination takes precedence over waiting on a possibly re-entrant mutex.
pub(crate) fn try_force_kill_active_runtimes() {
    try_for_each_active_runtime_process_id(ACTIVE_RUNTIME_PROCESS_IDS.get(), |process_id| {
        #[cfg(unix)]
        {
            use nix::sys::signal::{Signal, killpg};
            use nix::unistd::Pid;

            if let Ok(process_group_id) = i32::try_from(process_id) {
                let _ = killpg(Pid::from_raw(process_group_id), Signal::SIGKILL);
            }
        }
        #[cfg(windows)]
        {
            use windows_sys::Win32::Foundation::CloseHandle;
            use windows_sys::Win32::System::Threading::{
                OpenProcess, PROCESS_TERMINATE, TerminateProcess,
            };

            // SAFETY: the returned process handle is checked, used only for
            // termination, and closed in the same branch.
            let process = unsafe { OpenProcess(PROCESS_TERMINATE, 0, process_id) };
            if !process.is_null() {
                // SAFETY: this branch owns a live terminate-capable handle.
                let _ = unsafe { TerminateProcess(process, 1) };
                // SAFETY: this branch owns the handle returned above.
                let _ = unsafe { CloseHandle(process) };
            }
        }
        #[cfg(not(any(unix, windows)))]
        let _ = process_id;
    });
}

