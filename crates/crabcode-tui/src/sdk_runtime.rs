struct WriterAck {
    completed_at: Instant,
    result: Result<WriteReceipt, SendError>,
}

enum WriterAckTarget {
    Blocking(mpsc::SyncSender<WriterAck>),
    NonBlocking {
        delivery_id: OutboundDeliveryId,
        sender: mpsc::Sender<AsyncWriterAck>,
        ready: Arc<Notify>,
    },
}

impl WriterAckTarget {
    fn complete(self, ack: WriterAck) {
        match self {
            Self::Blocking(sender) => {
                let _ = sender.send(ack);
            }
            Self::NonBlocking {
                delivery_id,
                sender,
                ready,
            } => {
                if sender.send(AsyncWriterAck { delivery_id, ack }).is_ok() {
                    ready.notify_one();
                }
            }
        }
    }
}

