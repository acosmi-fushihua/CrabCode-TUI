struct NonBlockingOutboundState {
    next_delivery_id: u64,
    pending: VecDeque<PendingOutboundFrame>,
    in_flight: HashMap<OutboundDeliveryId, InFlightOutboundFrame>,
    completed: VecDeque<QueuedOutboundCompletion>,
    reserved_bytes: usize,
    frame_capacity: usize,
    byte_capacity: usize,
    ack_rx: mpsc::Receiver<AsyncWriterAck>,
}

impl NonBlockingOutboundState {
    fn live_frames(&self) -> usize {
        self.pending
            .len()
            .saturating_add(self.in_flight.len())
            .saturating_add(self.completed.len())
    }

    fn reserve_delivery_id(&mut self) -> Result<OutboundDeliveryId, OutboundSubmitError> {
        let id = OutboundDeliveryId(self.next_delivery_id);
        self.next_delivery_id = self
            .next_delivery_id
            .checked_add(1)
            .ok_or(OutboundSubmitError::DeliveryIdExhausted)?;
        Ok(id)
    }

    fn has_capacity_for(&self, encoded_len: usize) -> bool {
        self.live_frames() < self.frame_capacity
            && self.reserved_bytes.saturating_add(encoded_len) <= self.byte_capacity
    }

    fn queue_full_error(&self) -> OutboundSubmitError {
        OutboundSubmitError::QueueFull {
            frame_capacity: self.frame_capacity,
            byte_capacity: self.byte_capacity,
            queued_frames: self.live_frames(),
            queued_bytes: self.reserved_bytes,
        }
    }

    fn push_completion(
        &mut self,
        id: OutboundDeliveryId,
        encoded_len: usize,
        result: Result<WriteReceipt, SendError>,
    ) {
        self.completed.push_back(QueuedOutboundCompletion {
            encoded_len,
            completion: OutboundCompletion { id, result },
        });
    }

    fn next_deadline(&self) -> Option<Instant> {
        self.pending
            .iter()
            .map(|frame| frame.deadline)
            .chain(self.in_flight.values().map(|frame| frame.deadline))
            .min()
    }
}

