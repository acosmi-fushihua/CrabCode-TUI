#[derive(Debug, Clone)]
pub struct TransportLimits {
    pub max_stdout_frame_bytes: usize,
    pub max_stderr_frame_bytes: usize,
    pub max_outbound_frame_bytes: usize,
    pub stdout_event_capacity: usize,
    pub stdout_queue_bytes: usize,
    pub stderr_event_capacity: usize,
    pub stderr_queue_bytes: usize,
    pub writer_capacity: usize,
    pub writer_queue_bytes: usize,
    /// One end-to-end deadline for reserving outbound bytes, entering the
    /// writer queue, and receiving the writer's flush acknowledgement.
    pub outbound_send_timeout: Duration,
    pub max_pending_control_requests_per_direction: usize,
    pub shutdown_timeout: Duration,
}

impl Default for TransportLimits {
    fn default() -> Self {
        Self {
            max_stdout_frame_bytes: 16 * 1024 * 1024,
            max_stderr_frame_bytes: 256 * 1024,
            max_outbound_frame_bytes: 16 * 1024 * 1024,
            stdout_event_capacity: 256,
            stdout_queue_bytes: 32 * 1024 * 1024,
            stderr_event_capacity: 128,
            stderr_queue_bytes: 2 * 1024 * 1024,
            writer_capacity: 64,
            writer_queue_bytes: 32 * 1024 * 1024,
            outbound_send_timeout: Duration::from_secs(5),
            max_pending_control_requests_per_direction: 1024,
            shutdown_timeout: Duration::from_secs(5),
        }
    }
}

impl TransportLimits {
    fn validate(&self) -> Result<(), SpawnError> {
        for (name, value) in [
            ("max_stdout_frame_bytes", self.max_stdout_frame_bytes),
            ("max_stderr_frame_bytes", self.max_stderr_frame_bytes),
            ("max_outbound_frame_bytes", self.max_outbound_frame_bytes),
            ("stdout_event_capacity", self.stdout_event_capacity),
            ("stdout_queue_bytes", self.stdout_queue_bytes),
            ("stderr_event_capacity", self.stderr_event_capacity),
            ("stderr_queue_bytes", self.stderr_queue_bytes),
            ("writer_capacity", self.writer_capacity),
            ("writer_queue_bytes", self.writer_queue_bytes),
            (
                "max_pending_control_requests_per_direction",
                self.max_pending_control_requests_per_direction,
            ),
        ] {
            if value == 0 {
                return Err(SpawnError::InvalidLimits(format!(
                    "{name} must be greater than zero"
                )));
            }
        }
        if self.stdout_queue_bytes < self.max_stdout_frame_bytes {
            return Err(SpawnError::InvalidLimits(
                "stdout_queue_bytes must hold at least one maximum stdout frame".to_string(),
            ));
        }
        if self.stderr_queue_bytes < self.max_stderr_frame_bytes {
            return Err(SpawnError::InvalidLimits(
                "stderr_queue_bytes must hold at least one maximum stderr frame".to_string(),
            ));
        }
        if self.writer_queue_bytes < self.max_outbound_frame_bytes {
            return Err(SpawnError::InvalidLimits(
                "writer_queue_bytes must hold at least one maximum outbound frame".to_string(),
            ));
        }
        if self.outbound_send_timeout.is_zero() {
            return Err(SpawnError::InvalidLimits(
                "outbound_send_timeout must be greater than zero".to_string(),
            ));
        }
        if Instant::now()
            .checked_add(self.outbound_send_timeout)
            .is_none()
        {
            return Err(SpawnError::InvalidLimits(
                "outbound_send_timeout is too large for a monotonic deadline".to_string(),
            ));
        }
        if self.shutdown_timeout.is_zero() {
            return Err(SpawnError::InvalidLimits(
                "shutdown_timeout must be greater than zero".to_string(),
            ));
        }
        if Instant::now().checked_add(self.shutdown_timeout).is_none() {
            return Err(SpawnError::InvalidLimits(
                "shutdown_timeout is too large for a monotonic deadline".to_string(),
            ));
        }
        Ok(())
    }
}

