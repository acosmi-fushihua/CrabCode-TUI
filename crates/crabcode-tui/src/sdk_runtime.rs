    pub fn send_control_request(
        &self,
        request_id: impl Into<String>,
        request: Value,
    ) -> Result<WriteReceipt, SendError> {
        let request_id = request_id.into();
        let subtype = validate_outbound_control_request(&request_id, &request)?;
        {
            let mut correlations = self
                .correlations
                .lock()
                .unwrap_or_else(|poison| poison.into_inner());
            if correlations.outbound_requests.contains_key(&request_id)
                || correlations
                    .outbound_delivery_reservations
                    .contains_key(&request_id)
                || correlations
                    .private_runtime_actions
                    .contains_key(&request_id)
                || correlations
                    .private_runtime_delivery_reservations
                    .contains_key(&request_id)
            {
                return Err(SendError::Correlation(format!(
                    "duplicate outbound request id `{request_id}`"
                )));
            }
            if correlations.outbound_request_count() >= correlations.max_pending_per_direction {
                return Err(SendError::Correlation(format!(
                    "outbound control request limit ({}) exceeded",
                    correlations.max_pending_per_direction
                )));
            }
            correlations
                .outbound_requests
                .insert(request_id.clone(), subtype.clone());
        }
        let result = self.send_raw(json!({
            "type": "control_request",
            "request_id": request_id,
            "request": request
        }));
        if result.is_err() {
            self.correlations
                .lock()
                .unwrap_or_else(|poison| poison.into_inner())
                .outbound_requests
                .remove(&request_id);
        }
        result
    }

